"""Create/audit the Linux CPython-3.11 offline Docker wheelhouse.

Run this from Windows only to *download* Linux wheels; it never installs them
into the Windows virtual environment. The generated lock and SHA-256 manifest
make the wheel set auditable before a Docker build consumes it.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from email.parser import BytesParser
from pathlib import Path
import subprocess
import sys
import zipfile


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_WHEELHOUSE = ROOT / "wheelhouse" / "linux-cp311"
FORBIDDEN = {"torch", "torchvision", "torchaudio", "nvidia-cublas-cu12", "nvidia-cudnn-cu12"}


def normalized(name: str) -> str:
    return name.lower().replace("_", "-").replace(".", "-")


def wheel_metadata(path: Path) -> tuple[str, str]:
    with zipfile.ZipFile(path) as archive:
        candidates = [name for name in archive.namelist() if name.endswith(".dist-info/METADATA")]
        if len(candidates) != 1:
            raise ValueError(f"Wheel lacks one unambiguous METADATA file: {path.name}")
        metadata = BytesParser().parsebytes(archive.read(candidates[0]))
    return normalized(metadata["Name"]), metadata["Version"]


def is_linux_cp311_or_universal(filename: str) -> bool:
    lowered = filename.lower()
    return lowered.endswith("-any.whl") or ("linux" in lowered and "x86_64" in lowered and "win" not in lowered)


def build_manifest(wheelhouse: Path) -> dict:
    wheels = sorted(wheelhouse.glob("*.whl"))
    if not wheels:
        raise ValueError(f"No wheels found in {wheelhouse}")
    packages: dict[str, dict[str, str]] = {}
    for wheel in wheels:
        if not is_linux_cp311_or_universal(wheel.name):
            raise ValueError(f"Non-Linux/CPython-3.11 wheel is not allowed: {wheel.name}")
        name, version = wheel_metadata(wheel)
        if name in FORBIDDEN:
            raise ValueError(f"PyTorch/CUDA wheel must not be in this wheelhouse: {wheel.name}")
        digest = hashlib.sha256(wheel.read_bytes()).hexdigest()
        existing = packages.get(name)
        if existing and existing["version"] != version:
            raise ValueError(f"Multiple versions for {name}: {existing['version']} and {version}")
        packages[name] = {"version": version, "filename": wheel.name, "sha256": digest}
    return {"target": "manylinux_2_17_x86_64 / CPython 3.11", "wheel_count": len(wheels), "packages": packages}


def write_lock_and_manifest(wheelhouse: Path) -> tuple[Path, Path]:
    manifest = build_manifest(wheelhouse)
    lock = ROOT / "requirements-docker.lock.txt"
    lines = [
        "# Generated by tools/build_linux_wheelhouse.py; Linux CPython 3.11 only.",
        "# PyTorch/TorchVision/CUDA are intentionally supplied by the base image.",
    ]
    lines.extend(
        f"{name}=={entry['version']} --hash=sha256:{entry['sha256']}"
        for name, entry in sorted(manifest["packages"].items())
    )
    lock.write_text("\n".join(lines) + "\n", encoding="utf-8")
    manifest_path = wheelhouse / "WHEELHOUSE_MANIFEST.json"
    manifest_path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return lock, manifest_path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--wheelhouse", type=Path, default=DEFAULT_WHEELHOUSE)
    parser.add_argument("--download", action="store_true", help="Download the pinned direct requirements before auditing.")
    args = parser.parse_args()
    if args.download:
        args.wheelhouse.mkdir(parents=True, exist_ok=True)
        command = [
            sys.executable, "-m", "pip", "download", "--dest", str(args.wheelhouse),
            "--platform", "manylinux_2_17_x86_64", "--implementation", "cp", "--python-version", "311",
            "--abi", "cp311", "--only-binary=:all:", "-r", str(ROOT / "requirements-docker.txt"),
        ]
        subprocess.run(command, check=True)
    lock, manifest = write_lock_and_manifest(args.wheelhouse)
    print(json.dumps({"lock": str(lock), "manifest": str(manifest), "wheelhouse": str(args.wheelhouse)}, indent=2))


if __name__ == "__main__":
    main()
